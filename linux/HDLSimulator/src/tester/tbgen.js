'use strict';
/* global TS, Inst, Stim, Fmt, LogicLiteral, VerilogLexer, VerilogParser, TimeUnits, BitsFormat, PathUtil, Host, Library, pinKey, pinEq */
// Testbench generator and stimulus previews. Port of TBGen.swift and Waves.swift.

function problem(severity, message, extra = {}) { return Object.assign({ severity, message, instance: null, pin: null, wire: null }, extra); }

class TBGenerator {
  constructor(state, library) { this.state = state; this.library = library; } // library: ModuleInfo[]
  get topName() { return 'tb_' + Fmt.identifier(this.state.name); }
  get vcdName() { return Fmt.identifier(this.state.name) + '.vcd'; }

  generate(date = new Date()) {
    const st = this.state;
    const problems = [];
    const L = [];
    const top = this.topName;
    const u = st.unit;
    const duts = TS.duts(st), sources = TS.sources(st);

    if (!duts.length) problems.push(problem('error', 'The test has no DUTs. Drag a module from Available DUTs onto the canvas.'));
    if (st.duration <= 0) problems.push(problem('error', 'Test duration must be greater than 0.'));
    if (TimeUnits.exponent(st.precision) > TimeUnits.exponent(st.unit)) {
      problems.push(problem('error', `Time precision (${st.precision}) must not be coarser than the time unit (${st.unit}).`));
    }
    const seenNames = new Set();
    for (const inst of st.instances) {
      if (!Fmt.isIdentifier(inst.name)) problems.push(problem('error', `“${inst.name}” is not a valid name.`, { instance: inst.id }));
      if (seenNames.has(inst.name)) problems.push(problem('error', `Two blocks are named ${inst.name}.`, { instance: inst.id }));
      seenNames.add(inst.name);
    }

    const envs = new Map(), widths = new Map();
    for (const inst of st.instances) {
      const env = Inst.paramValues(inst);
      envs.set(inst.id, env);
      for (const p of inst.ports) { const r = Inst.resolve(inst, p, env); if (r) widths.set(pinKey({ instance: inst.id, pin: p.name }), r); }
    }

    const usedNets = new Set([top]);
    const unique = (base) => {
      let n = base, k = 2;
      while (usedNets.has(n) || VerilogParser.keywords.has(n)) { n = `${base}_${k}`; k++; }
      usedNets.add(n);
      return n;
    };
    const nets = new Map();
    for (const s of sources) nets.set(pinKey({ instance: s.id, pin: 'out' }), unique(s.name));
    for (const inst of duts) usedNets.add(inst.name);

    const driverOf = new Map(); // key(to) -> from ref
    for (const w of st.wires) {
      const fromInst = TS.instance(st, w.from.instance), toInst = TS.instance(st, w.to.instance);
      const fromPort = fromInst && fromInst.ports.find((p) => p.name === w.from.pin);
      const toPort = toInst && toInst.ports.find((p) => p.name === w.to.pin);
      if (!fromPort || !toPort) {
        problems.push(problem('warning', 'A wire points to a pin that no longer exists and is ignored.', { wire: w.id }));
        continue;
      }
      const label = `${TS.describe(st, w.from)} → ${TS.describe(st, w.to)}`;
      if (!(fromPort.dir === 'output' && toPort.dir === 'input' && !Inst.isSource(toInst))) {
        problems.push(problem('warning', `Wire ${label} must go from an output to an input; it is ignored.`, { wire: w.id }));
        continue;
      }
      const why = fromPort.unsupported ?? toPort.unsupported;
      if (why != null) { problems.push(problem('warning', `Wire ${label} is ignored: ${why}.`, { wire: w.id })); continue; }
      if (driverOf.has(pinKey(w.to))) {
        problems.push(problem('error', `${TS.describe(st, w.to)} has more than one wire driving it.`, { instance: w.to.instance, pin: w.to.pin, wire: w.id }));
        continue;
      }
      driverOf.set(pinKey(w.to), w.from);
      const a = (widths.get(pinKey(w.from)) || {}).width, b = (widths.get(pinKey(w.to)) || {}).width;
      if (a != null && b != null && a !== b) {
        problems.push(problem('warning', `Wire ${label} joins ${a} bit${a === 1 ? '' : 's'} to ${b} bit${b === 1 ? '' : 's'}; ` +
          (a > b ? 'the upper bits are dropped.' : 'the upper bits are 0.'), { wire: w.id }));
      }
    }

    for (const inst of duts) {
      for (const p of inst.ports) {
        if (p.unsupported != null) continue;
        const ref = { instance: inst.id, pin: p.name };
        if (p.dir === 'input' && driverOf.has(pinKey(ref))) continue;
        nets.set(pinKey(ref), unique(`${inst.name}_${p.name}`));
      }
    }
    const net = (ref) => { const d = driverOf.get(pinKey(ref)); return d ? nets.get(pinKey(d)) : nets.get(pinKey(ref)); };

    const pad2 = (n) => String(n).padStart(2, '0');
    const dateText = `${date.getFullYear()}-${pad2(date.getMonth() + 1)}-${pad2(date.getDate())} ${pad2(date.getHours())}:${pad2(date.getMinutes())}`;
    L.push('// ============================================================================');
    L.push(`// ${top}.v — generated by HDL Tester on ${dateText}`);
    L.push(`// Test: ${st.name}   ·   duration ${Fmt.num(st.duration)} ${u}`);
    L.push('// DUTs: ' + (duts.length ? duts.map((d) => `${d.name} (${d.moduleName})`).join(', ') : '(none)'));
    if (sources.length) L.push('// Sources: ' + sources.map((s) => s.name).join(', '));
    if (driverOf.size) {
      L.push('// Wires: ' + st.wires.filter((w) => { const d = driverOf.get(pinKey(w.to)); return d && pinEq(d, w.from); })
        .map((w) => `${TS.describe(st, w.from)} → ${TS.describe(st, w.to)}`).join(', '));
    }
    L.push('// This file is regenerated on every run; edit the test in HDL Tester instead.');
    L.push('// ============================================================================');
    L.push(`\`timescale 1${u}/1${st.precision}`);
    L.push('');
    L.push(`module ${top};`);
    L.push('');

    const rangeText = (ref) => { const r = widths.get(pinKey(ref)); return r && r.hasRange ? `[${r.msb}:${r.lsb}]` : ''; };
    const stimBlocks = [], logBlocks = [];

    if (sources.length) {
      L.push('  // ---------------------------------------------------------------------------');
      L.push('  // Sources (each can drive several DUT inputs)');
      L.push('  // ---------------------------------------------------------------------------');
      const rows = sources.map((s) => { const ref = { instance: s.id, pin: 'out' }; return [rangeText(ref), nets.get(pinKey(ref))]; });
      const rw = rows.reduce((m, r) => Math.max(m, r[0].length), 0);
      for (const [r, n] of rows) L.push('  reg ' + (rw > 0 ? r + ' '.repeat(rw - r.length + 1) : '') + `${n};`);
      L.push('');
      for (const s of sources) {
        const ref = { instance: s.id, pin: 'out' };
        const fanout = TS.wiresFrom(st, ref).filter((w) => { const d = driverOf.get(pinKey(w.to)); return d && pinEq(d, ref); }).length;
        if (fanout === 0) problems.push(problem('warning', `Source ${s.name} is not wired to anything.`, { instance: s.id, pin: 'out' }));
        const wd = widths.get(pinKey(ref));
        const [code, probs] = new StimulusCode(Inst.stimulus(s, 'out'), nets.get(pinKey(ref)), wd ? wd.width : null, u, s.name, s.id, 'out').emit();
        problems.push(...probs);
        stimBlocks.push(...code, '');
      }
    }

    for (const inst of duts) {
      L.push('  // ---------------------------------------------------------------------------');
      L.push(`  // ${inst.name} : ${inst.moduleName}   (${PathUtil.basename(inst.filePath)})`);
      L.push('  // ---------------------------------------------------------------------------');
      const needParamDecls = inst.ports.some((p) => !widths.has(pinKey({ instance: inst.id, pin: p.name })));
      const prefix = inst.name + '_';
      if (needParamDecls) {
        for (const p of inst.params) {
          let text = p.value;
          const o = inst.paramOverrides[p.name];
          if (!p.isLocal && o != null && o.trim()) text = o;
          L.push(`  localparam ${prefix}${p.name} = ${this.renameParams(text, inst, prefix)};`);
        }
      }
      const conns = [], declRows = [];
      for (const p of inst.ports) {
        const ref = { instance: inst.id, pin: p.name };
        if (p.unsupported != null) {
          problems.push(problem('warning', `${inst.name}.${p.name} is left unconnected: ${p.unsupported}.`, { instance: inst.id, pin: p.name }));
          conns.push([p.name, '', null]);
          continue;
        }
        const d = driverOf.get(pinKey(ref));
        if (p.dir === 'input' && d) { conns.push([p.name, nets.get(pinKey(d)) || '', `wired from ${TS.describe(st, d)}`]); continue; }
        const n = nets.get(pinKey(ref));
        conns.push([p.name, n, null]);
        let range = rangeText(ref);
        if (!widths.has(pinKey(ref))) {
          problems.push(problem('warning', `Could not compute the width of ${inst.name}.${p.name}; the testbench uses the expression instead.`, { instance: inst.id, pin: p.name }));
          range = p.ranges.map((r) => `[${this.renameParams(r.msb, inst, prefix)}:${this.renameParams(r.lsb, inst, prefix)}]`).join('');
        }
        const signed = p.isSigned || (PortInfoUtil.isIntegerType(p) && !p.dataType.includes('unsigned')) ? ' signed' : '';
        if (p.dir === 'input') {
          problems.push(problem('warning', `${inst.name}.${p.name} is not wired, so it floats (z). Wire a source or a DUT output to it.`, { instance: inst.id, pin: p.name }));
          conns[conns.length - 1][2] = 'not wired: floats (z)';
        }
        declRows.push(['wire' + signed, range, n]);
      }
      const typeW = declRows.length ? Math.max(...declRows.map((r) => r[0].length)) : 4;
      const rangeW = declRows.length ? Math.max(...declRows.map((r) => r[1].length)) : 0;
      for (const [t, r, n] of declRows) {
        L.push(`  ${t}${' '.repeat(typeW - t.length + 1)}${rangeW > 0 ? r + ' '.repeat(rangeW - r.length + 1) : ''}${n};`);
      }
      const overrides = inst.params.filter((p) => !p.isLocal).map((p) => {
        const o = (inst.paramOverrides[p.name] || '').trim();
        return o ? [p.name, needParamDecls ? prefix + p.name : o] : null;
      }).filter(Boolean);
      L.push('');
      if (!overrides.length) L.push(`  ${inst.moduleName} ${inst.name} (`);
      else {
        L.push(`  ${inst.moduleName} #(`);
        overrides.forEach(([n, v], k) => L.push(`    .${n}(${v})` + (k < overrides.length - 1 ? ',' : '')));
        L.push(`  ) ${inst.name} (`);
      }
      const nameW = conns.reduce((m, c) => Math.max(m, c[0].length), 0);
      const connW = conns.reduce((m, c) => Math.max(m, c[1].length + 3 + c[0].length), 0);
      conns.forEach(([p, n, comment], k) => {
        let line = `    .${p}${' '.repeat(nameW - p.length)} (${n})` + (k < conns.length - 1 ? ',' : '');
        if (comment != null) line += ' '.repeat(Math.max(1, connW + 8 - line.length)) + '// ' + comment;
        L.push(line);
      });
      L.push('  );');
      L.push('');
      for (const name of inst.logged) {
        const ref = { instance: inst.id, pin: name };
        const p = inst.ports.find((q) => q.name === name);
        const n = net(ref);
        if (!p || !n) continue;
        const wd = widths.get(pinKey(ref));
        const w = wd ? wd.width : 2;
        const fmt = w === 1 ? '%b' : '0x%h (%0d)';
        const args = w === 1 ? n : `${n}, ${n}`;
        logBlocks.push(`  always @(${n}) $display("%t  ${inst.name}.${p.name} = ${fmt}", $time, ${args});`);
      }
    }

    if (stimBlocks.length) {
      L.push('  // ===== Sources ==============================================================');
      L.push('');
      L.push(...stimBlocks);
    }
    if (logBlocks.length) {
      L.push('  // ===== Output log ===========================================================');
      L.push(...logBlocks);
      L.push('');
    }
    const digits = Math.max(0, TimeUnits.exponent(u) - TimeUnits.exponent(st.precision));
    L.push('  // ===== Waveform dump & end of test ===========================================');
    L.push('  initial begin');
    L.push(`    $timeformat(${TimeUnits.exponent(u)}, ${digits}, " ${u}", 0);`);
    L.push(`    $dumpfile("${this.vcdName}");`);
    L.push(`    $dumpvars(0, ${top});`);
    L.push(`    #${Fmt.num(st.duration)};`);
    L.push('    $display("HDL Tester: simulation finished at %t", $time);');
    L.push('    $finish;');
    L.push('  end');
    L.push('');
    L.push('endmodule');
    L.push('');

    const sourceFiles = this.sourceFiles(problems);
    return { topName: top, source: L.join('\n'), problems, sourceFiles, vcdName: this.vcdName };
  }

  renameParams(expr, inst, prefix) {
    const names = new Set(inst.params.map((p) => p.name));
    const toks = VerilogLexer.lex(expr);
    if (!toks.length) return expr;
    let out = '', last = 0;
    for (const t of toks) {
      out += expr.slice(last, t.start);
      out += (t.kind === 'ident' && names.has(t.text)) ? prefix + t.text : t.text;
      last = t.end;
    }
    return out + expr.slice(last);
  }

  sourceFiles(problems) {
    const files = [], seenFiles = new Set(), visited = new Set();
    const add = (p) => { const k = PathUtil.normalize(p); if (!seenFiles.has(k)) { seenFiles.add(k); files.push(p); } };
    const lookup = (name, prefer) => {
      const all = this.library.filter((m) => m.name === name);
      return all.find((m) => prefer != null && Library.samePath(m.file, prefer)) || all[0] || null;
    };
    const visit = (name, prefer) => {
      if (visited.has(name)) return;
      visited.add(name);
      const m = lookup(name, prefer);
      if (!m) return;
      add(m.file);
      for (const sub of m.instantiates) visit(sub, m.file);
    };
    for (const inst of TS.duts(this.state)) {
      if (Host.fs.exists(inst.filePath)) add(inst.filePath);
      else {
        const m = lookup(inst.moduleName, null);
        if (m) add(m.file);
        else problems.push(problem('error', `Source file for ${inst.moduleName} not found: ${inst.filePath}`, { instance: inst.id }));
      }
      visit(inst.moduleName, inst.filePath);
    }
    return files;
  }
}

class StimulusCode {
  constructor(stim, target, width, unit, label, instance, pin) {
    Object.assign(this, { stim, target, width, unit, label, instance, pin });
  }
  problem(msg, sev = 'error') { return problem(sev, `${this.label}: ${msg}`, { instance: this.instance, pin: this.pin }); }
  lit(text, what, probs) {
    const l = LogicLiteral.parse(text);
    if (!l) { probs.push(this.problem(`“${text}” is not a valid ${what} value.`)); return "'bx"; }
    if (this.width != null && l.size != null && l.size > this.width) {
      probs.push(this.problem(`value ${text} is wider than the pin (${this.width} bits) and will be truncated.`, 'warning'));
    }
    return LogicLiteral.verilog(l, this.width);
  }
  emit() {
    const p = [], c = [];
    const s = this.stim, t = this.target, un = this.unit, label = this.label, d = Fmt.num;
    switch (s.kind) {
      case 'constant': {
        const v = this.lit(s.constant, 'constant', p);
        c.push(`  // ${label}: constant ${s.constant}`, `  initial ${t} = ${v};`);
        break;
      }
      case 'clock': {
        if (!(s.period > 0)) { p.push(this.problem('clock period must be greater than 0.')); return [[`  initial ${t} = 1'b0;`], p]; }
        const duty = Math.min(Math.max(s.duty, 0.0001), 99.9999);
        if (s.duty <= 0 || s.duty >= 100) p.push(this.problem('duty cycle must be between 0 and 100 %.'));
        if (this.width != null && this.width !== 1) p.push(this.problem(`a clock on a ${this.width}-bit pin drives only bit 0.`, 'warning'));
        const high = s.period * duty / 100, low = s.period - high;
        c.push(`  // ${label}: clock, period ${d(s.period)} ${un} (${Fmt.frequency(s.period, this.unit)}), ${d(duty)}% duty` +
          (s.clockDelay > 0 ? `, starts after ${d(s.clockDelay)} ${un}` : ''));
        c.push('  initial begin', `    ${t} = 1'b${s.startHigh ? 1 : 0};`);
        if (s.clockDelay > 0) c.push(`    #${d(s.clockDelay)};`);
        c.push('    forever begin');
        if (s.startHigh) c.push(`      #${d(high)} ${t} = 1'b0;`, `      #${d(low)} ${t} = 1'b1;`);
        else c.push(`      #${d(low)} ${t} = 1'b1;`, `      #${d(high)} ${t} = 1'b0;`);
        c.push('    end', '  end');
        break;
      }
      case 'sequence': {
        const steps = Stim.relativeSteps(s);
        const total = steps.reduce((a, x) => a + x.delay, 0);
        let loop = s.seqRepeat;
        if (loop && total <= 0) { p.push(this.problem('a repeating sequence needs a total delay greater than 0; it will run once.')); loop = false; }
        c.push(`  // ${label}: sequence of ${steps.length} step${steps.length === 1 ? '' : 's'}` + (loop ? ', repeating' : ''));
        c.push('  initial begin', `    ${t} = ${this.lit(s.seqInitial, 'initial', p)};`);
        const ind = loop ? '      ' : '    ';
        if (loop) c.push('    forever begin');
        for (const x of steps) {
          if (x.delay < 0) p.push(this.problem('step delays cannot be negative.'));
          const v = this.lit(x.value, 'step', p);
          c.push(x.delay > 0 ? `${ind}#${d(x.delay)} ${t} = ${v};` : `${ind}${t} = ${v};`);
        }
        if (loop) c.push('    end');
        c.push('  end');
        break;
      }
      case 'bitstream': {
        const toks = Stim.streamTokens(s, this.width);
        if (!toks.length) p.push(this.problem('the bit stream is empty.', 'warning'));
        if (!(s.bitTime > 0)) { p.push(this.problem('bit time must be greater than 0.')); return [[`  initial ${t} = ${this.lit(s.bitIdle, 'idle', p)};`], p]; }
        const idle = this.lit(s.bitIdle, 'idle', p);
        c.push(`  // ${label}: bit stream of ${toks.length} value${toks.length === 1 ? '' : 's'}, ${d(s.bitTime)} ${un} each` + (s.bitRepeat ? ', repeating' : ''));
        c.push('  initial begin', `    ${t} = ${idle};`);
        if (s.bitDelay > 0) c.push(`    #${d(s.bitDelay)};`);
        const ind = s.bitRepeat ? '      ' : '    ';
        if (s.bitRepeat && toks.length) c.push('    forever begin');
        for (const tok of toks) {
          const v = this.width === 1 && tok.length === 1 ? `1'b${tok}` : this.lit(tok, 'bit stream', p);
          c.push(`${ind}${t} = ${v}; #${d(s.bitTime)};`);
        }
        if (s.bitRepeat && toks.length) c.push('    end'); else c.push(`    ${t} = ${idle};`);
        c.push('  end');
        break;
      }
      case 'counter': {
        if (!(s.countInterval > 0)) { p.push(this.problem('counter interval must be greater than 0.')); return [[`  initial ${t} = ${this.lit(s.countStart, 'start', p)};`], p]; }
        const start = this.lit(s.countStart, 'start', p), step = this.lit(s.countStep, 'step', p);
        c.push(`  // ${label}: counter from ${s.countStart}, step ${s.countStep} every ${d(s.countInterval)} ${un}`);
        c.push('  initial begin', `    ${t} = ${start};`);
        if (s.countDelay > 0) c.push(`    #${d(s.countDelay)};`);
        c.push(`    forever #${d(s.countInterval)} ${t} = ${t} + (${step});`, '  end');
        break;
      }
      default: {
        if (!(s.randInterval > 0)) { p.push(this.problem('random interval must be greater than 0.')); return [[`  initial ${t} = 0;`], p]; }
        const seed = `${this.target}_seed`;
        const words = Math.max(1, Math.floor(((this.width ?? 32) + 31) / 32));
        const rand = words === 1 ? `$random(${seed})` : '{' + new Array(words).fill(`$random(${seed})`).join(', ') + '}';
        c.push(`  // ${label}: random value every ${d(s.randInterval)} ${un}, seed ${s.randSeed}`);
        c.push(`  integer ${seed};`, '  initial begin', `    ${seed} = ${s.randSeed};`, `    ${t} = 0;`);
        if (s.randDelay > 0) c.push(`    #${d(s.randDelay)};`);
        c.push('    forever begin', `      ${t} = ${rand};`, `      #${d(s.randInterval)};`, '    end', '  end');
      }
    }
    return [c, p];
  }
}

// ---------------------------------------------------------------- Stimulus preview

const StimulusPreview = (() => {
  const maxSegments = 20000;
  function segBits(t, bits) {
    if (bits.length === 1) {
      const b = bits[0];
      return { t, level: b === '0' ? 'low' : b === '1' ? 'high' : b, label: b };
    }
    if (bits.every((b) => b === 'x')) return { t, level: 'x', label: 'x' };
    if (bits.every((b) => b === 'z')) return { t, level: 'z', label: 'z' };
    return { t, level: 'bus', label: BitsFormat.hex(bits) };
  }
  function seg(t, text, width) {
    const l = LogicLiteral.parse(text);
    const bits = l && LogicLiteral.bits(l, Math.max(width, 1));
    return bits ? segBits(t, bits) : { t, level: 'x', label: '?' };
  }
  function segments(s, width, horizon) {
    const w = Math.max(width ?? 1, 1);
    const out = [];
    const add = (sg) => {
      const last = out[out.length - 1];
      if (last && last.level === sg.level && last.label === sg.label) return;
      if (last && last.t === sg.t) out.pop();
      out.push(sg);
    };
    switch (s.kind) {
      case 'constant': add(seg(0, s.constant, w)); break;
      case 'clock': {
        if (!(s.period > 0)) return [seg(0, 'x', 1)];
        const duty = Math.min(Math.max(s.duty, 0.0001), 99.9999);
        const high = s.period * duty / 100, low = s.period - high;
        let level = s.startHigh;
        add(seg(0, level ? '1' : '0', w));
        let t = s.clockDelay;
        while (t <= horizon && out.length < maxSegments) { t += level ? high : low; level = !level; add(seg(t, level ? '1' : '0', w)); }
        break;
      }
      case 'sequence': {
        add(seg(0, s.seqInitial, w));
        const steps = Stim.relativeSteps(s);
        const total = steps.reduce((a, x) => a + x.delay, 0);
        let t = 0;
        do {
          for (const x of steps) { t += Math.max(0, x.delay); if (t > horizon) break; add(seg(t, x.value, w)); }
        } while (s.seqRepeat && total > 0 && t <= horizon && out.length < maxSegments);
        break;
      }
      case 'bitstream': {
        add(seg(0, s.bitIdle, w));
        const toks = Stim.streamTokens(s, width);
        if (!(s.bitTime > 0) || !toks.length) break;
        let t = s.bitDelay;
        do {
          for (const tok of toks) { if (t > horizon) break; add(seg(t, tok, w)); t += s.bitTime; }
        } while (s.bitRepeat && t <= horizon && out.length < maxSegments);
        if (!s.bitRepeat && t <= horizon) add(seg(t, s.bitIdle, w));
        break;
      }
      case 'counter': {
        const sl = LogicLiteral.parse(s.countStart), tl = LogicLiteral.parse(s.countStep);
        const sb = sl && LogicLiteral.bits(sl, w), tb = tl && LogicLiteral.bits(tl, w);
        let v = sb && w <= 64 ? BitsFormat.uint(sb) : null;
        const step = tb ? BitsFormat.uint(tb) : null;
        if (v == null || step == null) { add(seg(0, s.countStart, w)); break; }
        const mask = (1n << BigInt(w)) - 1n;
        add(segBits(0, BitsFormat.bits(v, w)));
        if (!(s.countInterval > 0)) break;
        let t = s.countDelay + s.countInterval;
        while (t <= horizon && out.length < maxSegments) { v = (v + step) & mask; add(segBits(t, BitsFormat.bits(v, w))); t += s.countInterval; }
        break;
      }
      default: {
        add(segBits(0, BitsFormat.bits(0n, w)));
        if (!(s.randInterval > 0)) break;
        const M = (1n << 64n) - 1n;
        const A = 6364136223846793005n, C = 1442695040888963407n;
        let rng = (BigInt.asUintN(64, BigInt(s.randSeed)) * A + C) & M;
        let t = s.randDelay;
        while (t <= horizon && out.length < maxSegments) {
          let bits = [];
          while (bits.length < w) { rng = (rng * A + C) & M; bits = bits.concat(BitsFormat.bits(rng >> 11n, Math.min(53, w - bits.length))); }
          add(segBits(t, bits));
          t += s.randInterval;
        }
      }
    }
    return out;
  }
  function suggestedHorizon(s, duration) {
    let h;
    switch (s.kind) {
      case 'constant': h = duration; break;
      case 'clock': h = s.clockDelay + s.period * 8; break;
      case 'sequence': { const total = Stim.relativeSteps(s).reduce((a, x) => a + x.delay, 0); h = s.seqRepeat ? total * 2.5 : total * 1.25; break; }
      case 'bitstream': h = s.bitDelay + s.bitTime * Math.max(1, Stim.streamTokens(s, null).length) * (s.bitRepeat ? 1.5 : 1.2); break;
      case 'counter': h = s.countDelay + s.countInterval * 10; break;
      default: h = s.randDelay + s.randInterval * 10;
    }
    if (!(h > 0)) return Math.max(duration, 1);
    return Math.min(Math.max(h, 1e-9), Math.max(duration, 1e-9));
  }
  return { segments, suggestedHorizon };
})();

